import {test} from "node:test";
import assert from "node:assert/strict";
import {audit, build, clean} from "../logic.js";
const BASE = "https://example.org/sale";
const GOOD = BASE + "?utm_source=email&utm_medium=newsletter&utm_campaign=october";
const codes = (url) => audit(url).findings.map(f => f.code);
test("clean base URL", () => assert.deepEqual(codes(BASE), []));
test("valid full UTM", () => assert.deepEqual(codes(GOOD), []));
test("http warns", () => assert.ok(codes("http://example.org").includes("CLD101")));
test("reject scheme", () => assert.ok(codes("javascript:alert(1)").includes("CLD001")));
test("reject URL userinfo", () => assert.ok(codes("https://alice:secret@example.org").includes("CLD001")));
test("no domain", () => assert.ok(codes("https://").includes("CLD001")));
test("duplicate UTMs fail", () => assert.ok(codes(GOOD + "&utm_source=paid").includes("CLD002")));
test("ordinary duplicated filters allowed", () => assert.ok(!codes(BASE + "?tag=a&tag=b").includes("CLD002")));
test("partial campaign warns", () => assert.ok(codes(BASE + "?utm_medium=cpc").includes("CLD103")));
test("no campaign no warning", () => assert.ok(!codes(BASE + "?sku=2").includes("CLD103")));
test("empty campaign field fails", () => assert.ok(codes(BASE + "?utm_source=").includes("CLD004")));
test("case mismatch warns", () => assert.ok(codes(BASE + "?UTM_Source=x").includes("CLD102")));
test("email in value fails", () => assert.ok(codes(BASE + "?ref=user%40example.org").includes("CLD003")));
test("token field fails", () => assert.ok(codes(BASE + "?api_key=123").includes("CLD003")));
test("click tracking info", () => assert.ok(codes(BASE + "?fbclid=abc").includes("CLD201")));
test("fragment warning", () => assert.ok(codes(BASE + "#utm_campaign=abc").includes("CLD104")));
test("broken percent encoding", () => assert.ok(codes(BASE + "?x=%ZZ").includes("CLD001")));
test("redacted result", () => assert.ok(!JSON.stringify(audit(BASE + "?email=user%40example.org")).includes("user@")));
test("basic build", () => assert.equal(build(BASE, {source:"email", medium:"newsletter", campaign:"october"}),GOOD));
test("keeps product query", () => assert.ok(build(BASE + "?sku=2", {source:"a",medium:"b",campaign:"c"}).includes("sku=2")));
test("reject existing UTM", () => assert.throws(() => build(GOOD,{source:"a",medium:"b",campaign:"c"})));
test("replace old UTM", () => assert.equal((build(GOOD,{source:"a",medium:"b",campaign:"c"},true).match(/utm_source/g)||[]).length,1));
test("reject base email", () => assert.throws(() => build(BASE+"?email=foo",{source:"a",medium:"b",campaign:"c"})));
test("reject campaign email", () => assert.throws(() => build(BASE,{source:"user@example.org",medium:"b",campaign:"c"})));
test("reject blank campaign", () => assert.throws(() => build(BASE,{source:"a",medium:"b",campaign:""})));
test("encoded campaign", () => assert.ok(build(BASE,{source:"a",medium:"b",campaign:"big sale"}).includes("big+sale")));
test("clean tracking", () => assert.equal(clean(BASE+"?gclid=abc&sku=2").url,BASE+"?sku=2"));
test("clean personal query", () => assert.equal(clean(BASE+"?email=user%40example.org&sku=2").url,BASE+"?sku=2"));
test("count cleanup", () => assert.equal(clean(GOOD).removed,3));
test("clean preserves ordinary query", () => assert.equal(clean(BASE+"?tag=a&tag=b").removed,0));

